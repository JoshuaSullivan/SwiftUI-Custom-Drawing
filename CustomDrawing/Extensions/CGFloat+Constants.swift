import CoreGraphics

public extension CGFloat {
    /// 2π
    nonisolated static let twoPi: CGFloat = 2 * .pi

    /// π/2
    nonisolated static let halfPi: CGFloat = 0.5 * .pi
}

public extension Double {
    /// 2π
    nonisolated static let twoPi: Double = 2 * .pi

    /// π/2
    nonisolated static let halfPi: Double = 0.5 * .pi
}

public extension Float {
    /// 2π
    nonisolated static let twoPi: Float = 2 * .pi

    /// π/2
    nonisolated static let halfPi: Float = 0.5 * .pi
}

